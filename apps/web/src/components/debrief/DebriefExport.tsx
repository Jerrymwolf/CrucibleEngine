export function DebriefExport({
  data,
  onClose,
  className,
}: DebriefExportProps) {
  const { play: playSound } = useSound();
  const [downloadingPdf, setDownloadingPdf] = useState(false);
  const [downloadedPdf, setDownloadedPdf] = useState(false);
  const [downloadedJson, setDownloadedJson] = useState(false);
  const [copiedLink, setCopiedLink] = useState(false);
  const [showPreview, setShowPreview] = useState(false);
  const [email, setEmail] = useState('');
  const [emailSent, setEmailSent] = useState(false);

  const markdownContent = generateMarkdownReport(data);
  const jsonContent = generateJsonExport(data);

  const handleDownloadMarkdown = useCallback(() => {
    downloadFile(
      markdownContent,
      `debrief-${data.sessionCode}-${data.participantName}.md`,
      'text/markdown'
    );
    setDownloadedPdf(true);
    playSound('ui', 'success');
    setTimeout(() => setDownloadedPdf(false), 2000);
  }, [markdownContent, data.sessionCode, data.participantName, playSound]);

  const handleDownloadJson = useCallback(() => {
    downloadFile(
      jsonContent,
      `debrief-${data.sessionCode}-${data.participantName}.json`,
      'application/json'
    );
    setDownloadedJson(true);
    playSound('ui', 'success');
    setTimeout(() => setDownloadedJson(false), 2000);
  }, [jsonContent, data.sessionCode, data.participantName, playSound]);

  const handleCopyLink = useCallback(async () => {
    // In a real implementation, this would generate a shareable link
    const shareableLink = `${window.location.origin}/debrief/share/${data.sessionCode}/${btoa(data.participantName)}`;
    const success = await copyToClipboard(shareableLink);
    if (success) {
      setCopiedLink(true);
      playSound('ui', 'success');
      setTimeout(() => setCopiedLink(false), 2000);
    }
  }, [data.sessionCode, data.participantName, playSound]);

  const handleSendEmail = useCallback(async () => {
    if (!email.trim()) return;

    // In a real implementation, this would call an API to send the email
    setEmailSent(true);
    playSound('ui', 'success');
    setTimeout(() => setEmailSent(false), 3000);
  }, [email, playSound]);

  return (
    <div className={cn('space-y-6', className)}>
      {/* Header */}
      <div className="text-center">
        <h2 className="text-2xl font-bold mb-2">Export Your Debrief</h2>
        <p className="text-muted-foreground">
          Save your learning and share with your team
        </p>
      </div>

      {/* Export Options */}
      <div className="space-y-3">
        <ExportOption
          icon={FileText}
          title="Download Report"
          description="Get a formatted markdown report of your debrief"
          onClick={handleDownloadMarkdown}
          success={downloadedPdf}
        />

        <ExportOption
          icon={FileJson}
          title="Download Data"
          description="Export raw data as JSON for further analysis"
          onClick={handleDownloadJson}
          success={downloadedJson}
        />

        <ExportOption
          icon={Link2}
          title="Copy Shareable Link"
          description="Share your debrief summary with others"
          onClick={handleCopyLink}
          success={copiedLink}
        />
      </div>

      {/* Email Option */}
      <div className="p-4 border border-border rounded-xl space-y-3">
        <div className="flex items-center gap-3">
          <div className="p-3 rounded-lg bg-muted">
            <Mail className="h-5 w-5" />
          </div>
          <div>
            <h3 className="font-medium">Email Report to Yourself</h3>
            <p className="text-sm text-muted-foreground">
              Receive your debrief in your inbox
            </p>
          </div>
        </div>
        <div className="flex gap-2">
          <Input
            type="email"
            placeholder="Enter your email..."
            value={email}
            onChange={(e) => setEmail(e.target.value)}
            disabled={emailSent}
          />
          <Button
            onClick={handleSendEmail}
            disabled={!email.trim() || emailSent}
          >
            {emailSent ? (
              <>
                <Check className="h-4 w-4 mr-2" />
                Sent!
              </>
            ) : (
              'Send'
            )}
          </Button>
        </div>
      </div>

      {/* Preview Toggle */}
      <button
        type="button"
        onClick={() => setShowPreview((prev) => !prev)}
        className="flex items-center gap-2 text-sm text-muted-foreground hover:text-foreground transition-colors"
      >
        <Eye className="h-4 w-4" />
        {showPreview ? 'Hide Preview' : 'Preview Export'}
      </button>

      {/* Preview */}
      <AnimatePresence>
        {showPreview && (
          <motion.div
            initial={{ height: 0, opacity: 0 }}
            animate={{ height: 'auto', opacity: 1 }}
            exit={{ height: 0, opacity: 0 }}
            className="space-y-3 overflow-hidden"
          >
            <PreviewSection title="Markdown Report" content={markdownContent} />
            <PreviewSection title="JSON Data" content={jsonContent} />
          </motion.div>
        )}
      </AnimatePresence>

      {/* Close Button */}
      {onClose && (
        <Button variant="outline" className="w-full" onClick={onClose}>
          Done
        </Button>
      )}
    </div>
  );
}

export default DebriefExport;
