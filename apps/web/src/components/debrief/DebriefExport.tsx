'use client';

/**
 * DebriefExport Component
 *
 * Export and share debrief results in various formats.
 * Allows participants to save and share their learning.
 *
 * Features:
 * - PDF export with full debrief report
 * - JSON export for data analysis
 * - Shareable summary link
 * - Email report to self
 */

import { useState, useCallback } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { cn } from '@/lib/utils';
import { useSound } from '@/hooks/useSound';
import {
  Download,
  Share2,
  FileJson,
  FileText,
  Mail,
  Link2,
  Check,
  Copy,
  Loader2,
  ChevronDown,
  ChevronRight,
  Eye,
} from 'lucide-react';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';

// ============================================================================
// TYPES
// ============================================================================

export interface DebriefData {
  sessionCode: string;
  teamName: string;
  participantName: string;
  completedAt: string;

  // Values Discovery
  statedValues: {
    rank: number;
    name: string;
    definition: string;
  }[];
  commitment: string;

  // Decisions
  decisions: {
    timestamp: number;
    dilemmaTitle: string;
    optionChosen: string;
    rationale: string;
    valuesAlignment: 'aligned' | 'conflicted' | 'compromised';
    consequences: string[];
  }[];

  // Gap Analysis
  valueGaps: {
    valueName: string;
    statedScore: number;
    enactedScore: number;
    gap: number;
    evidence: string[];
  }[];

  // Rationalization
  rationalizationDetected: boolean;
  rationalizationSteps?: string[];

  // Transfer
  transferCommitments: string[];
  personalReflection?: string;
}

export interface DebriefExportProps {
  data: DebriefData;
  onClose?: () => void;
  className?: string;
}

