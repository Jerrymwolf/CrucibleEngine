function generateMarkdownReport(data: DebriefData): string {
  const lines: string[] = [];

  lines.push('# The Values Crucible - Debrief Report');
  lines.push('');
  lines.push(`**Session:** ${data.sessionCode}`);
  lines.push(`**Team:** ${data.teamName}`);
  lines.push(`**Participant:** ${data.participantName}`);
  lines.push(`**Completed:** ${new Date(data.completedAt).toLocaleString()}`);
  lines.push('');
  lines.push('---');
  lines.push('');

  // Values
  lines.push('## Stated Values');
  lines.push('');
  data.statedValues.forEach((value) => {
    lines.push(`${value.rank}. **${value.name}** - ${value.definition}`);
  });
  lines.push('');

  // Commitment
  lines.push('## Team Commitment');
  lines.push('');
  lines.push(`> ${data.commitment}`);
  lines.push('');

  // Decisions
  lines.push('## Key Decisions');
  lines.push('');
  data.decisions.forEach((decision, i) => {
    lines.push(`### Decision ${i + 1}: ${decision.dilemmaTitle}`);
    lines.push('');
    lines.push(`**Choice:** ${decision.optionChosen}`);
    lines.push('');
    lines.push(`**Rationale:** ${decision.rationale}`);
    lines.push('');
    lines.push(`**Values Alignment:** ${decision.valuesAlignment}`);
    lines.push('');
    if (decision.consequences.length > 0) {
      lines.push('**Consequences:**');
      decision.consequences.forEach((c) => lines.push(`- ${c}`));
      lines.push('');
    }
  });

  // Gap Analysis
  lines.push('## Values Gap Analysis');
  lines.push('');
  lines.push('| Value | Stated | Enacted | Gap |');
  lines.push('|-------|--------|---------|-----|');
  data.valueGaps.forEach((gap) => {
    lines.push(
      `| ${gap.valueName} | ${gap.statedScore}% | ${gap.enactedScore}% | ${gap.gap}% |`
    );
  });
  lines.push('');

  // Rationalization
  if (data.rationalizationDetected && data.rationalizationSteps) {
    lines.push('## Rationalization Pattern Detected');
    lines.push('');
    lines.push('The following drift pattern was observed:');
    lines.push('');
    data.rationalizationSteps.forEach((step, i) => {
      lines.push(`${i + 1}. ${step}`);
    });
    lines.push('');
  }

  // Transfer Commitments
  lines.push('## Personal Commitments');
  lines.push('');
  data.transferCommitments.forEach((commitment) => {
    lines.push(`- ${commitment}`);
  });
  lines.push('');

  if (data.personalReflection) {
    lines.push('## Personal Reflection');
    lines.push('');
    lines.push(data.personalReflection);
    lines.push('');
  }

  lines.push('---');
  lines.push('');
  lines.push('*Generated by The Values Crucible*');

  return lines.join('\n');
}

function generateJsonExport(data: DebriefData): string {
  return JSON.stringify(data, null, 2);
}

async function copyToClipboard(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
}

function downloadFile(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

